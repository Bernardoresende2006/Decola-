    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        if (this.titularTextField.getText().trim().isEmpty() || this.nCartaoTextField.getText().trim().isEmpty() || this.cvvTextField.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Preencha os dados de pagamento!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        this.pagamentoConfirmado = true;
        
        if(this.debitoCheckBox.isSelected()) this.formaSelecionada = "debito";
        else if(this.creditoCheckBox.isSelected()) this.formaSelecionada = "credito";
        
        this.dispose();
    }//GEN-LAST:event_btnConfirmarActionPerformed

    private void btnCancelarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelarActionPerformed
        this.pagamentoConfirmado = false;
        this.dispose();
    }//GEN-LAST:event_btnCancelarActionPerformed

